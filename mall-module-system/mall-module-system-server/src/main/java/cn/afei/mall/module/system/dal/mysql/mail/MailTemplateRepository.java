package cn.afei.mall.module.system.dal.mysql.mail;

import cn.afei.mall.framework.common.pojo.PageResult;
import cn.afei.mall.framework.jpa.core.query.LambdaSpecifications;
import cn.afei.mall.framework.jpa.core.repository.BaseRepositoryX;
import cn.afei.mall.module.system.controller.admin.mail.vo.template.MailTemplatePageReqVO;
import cn.afei.mall.module.system.dal.dataobject.mail.MailTemplateDO;

import java.util.List;

public interface MailTemplateRepository extends BaseRepositoryX<MailTemplateDO, Long> {

    default PageResult<MailTemplateDO> selectPage(MailTemplatePageReqVO pageReqVO) {
        return selectPage(pageReqVO, LambdaSpecifications.<MailTemplateDO>of()
                .eqIfPresent(MailTemplateDO::getStatus, pageReqVO.getStatus())
                .likeIfPresent(MailTemplateDO::getCode, pageReqVO.getCode())
                .likeIfPresent(MailTemplateDO::getName, pageReqVO.getName())
                .eqIfPresent(MailTemplateDO::getAccountId, pageReqVO.getAccountId())
                .betweenIfPresent(MailTemplateDO::getCreateTime, pageReqVO.getCreateTime())
                .orderByDesc(MailTemplateDO::getId)
                .build());
    }

    default Long selectCountByAccountId(Long accountId) {
        return selectCount(MailTemplateDO::getAccountId, accountId);
    }

    default MailTemplateDO selectByCode(String code) {
        return selectOne(MailTemplateDO::getCode, code);
    }

    default List<MailTemplateDO> selectListByStatus(Integer status) {
        return selectList(MailTemplateDO::getStatus, status);
    }

}
